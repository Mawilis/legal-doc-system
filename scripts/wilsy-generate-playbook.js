/**
 * @function ensureDirectory
 * @description Creates an output directory if it is missing.
 * @param {string} directory Directory path.
 * @returns {void}
 * @collaboration Playbook artifact writer and local Knowledge Base artifact generation.
 */
function ensureDirectory(directory = '') {
  fs.mkdirSync(directory, { recursive: true });
}

/**
 * @function repoPath
 * @description Converts a repo-relative artifact path into an absolute filesystem path.
 * @param {string} relativePath Repo-relative path.
 * @returns {string} Absolute path.
 * @collaboration Playbook markdown, JSON, PDF, and proof sidecar generation.
 */
function repoPath(relativePath = '') {
  return path.join(REPO_ROOT, relativePath);
}

/**
 * @function calculateFileHashes
 * @description Calculates release hashes for a generated artifact file.
 * @param {string} absolutePath Artifact path.
 * @returns {object} Hash packet.
 * @collaboration Knowledge Base proof sidecars, guard validation, and Vault integrity checks.
 */
function calculateFileHashes(absolutePath = '') {
  const buffer = fs.readFileSync(absolutePath);

  return {
    bytes: buffer.length,
    sha256: crypto.createHash('sha256').update(buffer).digest('hex'),
    sha512: crypto.createHash('sha512').update(buffer).digest('hex'),
    sha3: crypto.createHash('sha3-512').update(buffer).digest('hex'),
  };
}

/**
 * @function renderMarkdown
 * @description Renders the Knowledge Base playbook as a human-readable markdown source file.
 * @param {object} playbook Playbook model.
 * @returns {string} Markdown source.
 * @collaboration Knowledge Base guard markdown readiness and PDF/JSON artifact traceability.
 */
function renderMarkdown(playbook = PLAYBOOK) {
  const sourceRows = playbook.evidenceSources
    .map((source, index) => `${index + 1}. ${source.title} - ${source.url}\n   - Use in Wilsy OS: ${source.useInWilsy}\n   - Evidence: ${source.evidence}`)
    .join('\n\n');
  const sections = playbook.sections
    .map((section, index) => {
      const paragraphs = section.paragraphs.map((paragraph) => `${paragraph}`).join('\n\n');
      const bullets = section.bullets.map((bullet) => `- ${bullet}`).join('\n');
      return `## ${index + 1}. ${section.heading}\n\n${paragraphs}\n\n${bullets}`;
    })
    .join('\n\n---\n\n');

  return `# ${playbook.title}

Document class: ${playbook.documentClass}  
Product surface: ${playbook.productSurface}  
Source posture: ${playbook.sourcePosture}  
Owner: ${playbook.ownerEntity}  
Generated by: ${playbook.generatedByDisplayName}  
Prepared for: Investors, tenant users, operators, auditors, and future engineers  

---

${sections}

---

## Release Cadence

Trigger: ${playbook.releaseCadence.trigger}

Required artifacts:

${playbook.releaseCadence.requiredArtifacts.map((item) => `- ${item}`).join('\n')}

Required gates:

${playbook.releaseCadence.gates.map((item) => `- ${item}`).join('\n')}

---

## Forensic Sources

${sourceRows}

---

## File Contract

- Markdown path: ${playbook.paths.markdownPath}
- JSON path: ${playbook.paths.jsonPath}
- PDF path: ${playbook.paths.pdfPath}
- Proof path: ${playbook.paths.proofPath}
- PDF route: ${playbook.routes.pdfRoute}
- Vault route: ${playbook.routes.vaultRoute}
- Forbidden legacy PDF route: ${playbook.routes.forbiddenLegacyPdfRoute}
`;
}

