  traceId: {
    type: String,
    required: [true, 'Forensic Trace ID must be inherited from the Gateway.'],
    unique: true,
    index: true
  },
  inferenceType: {
    type: String,
    enum: [
      'REVENUE_FORECAST',
      'LEAD_SCORE',
      'DEAL_PREDICTION',
      'ANOMALY_DETECTION',
      'NLP_QUERY',
      'DOCUMENT_CLASSIFICATION',
      'PII_REDACTION',
      'COMPUTER_VISION',
      'EXECUTIVE_INTELLIGENCE' // 🆕 FG232 type
    ],
    required: true,
    index: true
  },
  inputVector: {
    type: Schema.Types.Mixed,
    required: [true, 'Input tensors/data must be preserved for reproducibility.']
  },
  outputData: {
    type: Schema.Types.Mixed,
    required: [true, 'AI Output must be recorded for institutional audit.']
  },
  confidenceScore: {
    type: Number,
    min: 0,
    max: 1,
    required: true
  },
  metadata: {
    modelVersion: { type: String, required: true },
    processingTimeMs: { type: Number, required: true },
    algorithmicStrategy: { type: String, default: 'DETERMINISTIC_ENSEMBLE' }
  },

  // ──────────────────────────────────────────────────────────────────────────
  // 🆕 FG232 EXECUTIVE INTELLIGENCE FIELDS (Phase 6.3)
