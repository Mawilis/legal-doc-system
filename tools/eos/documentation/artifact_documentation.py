from typing import Dict, List, Any, Optional
from tools.eos.documentation.documentation_contract import (
    DocumentationEntity,
    EntityKind,
    ArtifactSpec,
    VerificationStatus,
)


class ArtifactDocumentationGenerator:
    """
    Specialized documentation builder for tracking output artifacts, files,
    legal documents, and structured data payloads across Wilsy OS.
    """

    @staticmethod
    def generate_artifact_entity(
        urn: str,
        artifact_type: str,
        producer: str,
        consumer: str,
        purpose: str,
        retention_policy: str = "PERPETUAL_IMMUTABLE",
        schema_urn: str = "",
        version: str = "2.0.0",
    ) -> DocumentationEntity:
        """
        Constructs a DocumentationEntity specifically representing an output artifact contract.

        Args:
            urn: Target unique documentation URN.
            artifact_type: Standardized artifact classifier (e.g., 'PDF_LEGAL_BRIEF').
            producer: System component or engine producing the artifact.
            consumer: Target subsystem or client receiving the artifact.
            purpose: Executive description of the artifact's purpose.
            retention_policy: Institutional retention requirement.
            schema_urn: Optional URN referencing the structural data schema.
            version: Target version string.

        Returns:
            Validated DocumentationEntity contract instance.
        """
        artifact_spec = ArtifactSpec(
            artifact_type=artifact_type,
            producer=producer,
            consumer=consumer,
            retention_policy=retention_policy,
            schema_urn=schema_urn,
        )

        metadata = {
            "artifact_type": artifact_type,
            "producer": producer,
            "consumer": consumer,
            "retention_policy": retention_policy,
            "schema_urn": schema_urn,
        }

        return DocumentationEntity(
            urn=urn,
            kind=EntityKind.ARTIFACT,
            title=f"Artifact Contract: {artifact_type}",
            purpose=purpose,
            module_path=producer,
            version=version,
            architecture_summary=f"Output artifact generated by {producer} for consumption by {consumer}",
            lifecycle_stage="PRODUCTION",
            artifacts=[artifact_spec],
            metadata=metadata,
            verification_status=VerificationStatus.VERIFIED,
        )

    @staticmethod
    def generate_artifact_catalog(entities: List[DocumentationEntity]) -> Dict[str, Any]:
        """
        Aggregates artifact DocumentationEntity contracts into a system-wide artifact catalog.

        Args:
            entities: List of registered DocumentationEntity contracts.

        Returns:
            Dictionary cataloging all registered system artifacts.
        """
        catalog: Dict[str, Any] = {
            "total_artifacts": 0,
            "artifacts": [],
        }

        for entity in entities:
            if entity.kind != EntityKind.ARTIFACT:
                continue

            for art in entity.artifacts:
                catalog["artifacts"].append({
                    "urn": entity.urn,
                    "artifact_type": art.artifact_type,
                    "producer": art.producer,
                    "consumer": art.consumer,
                    "retention_policy": art.retention_policy,
                    "schema_urn": art.schema_urn,
                })

        catalog["total_artifacts"] = len(catalog["artifacts"])
        return catalog
