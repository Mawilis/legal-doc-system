class LegalMatterWorkflowTransitionError(ValueError):
    """Stable fail-closed workflow-transition validation failure."""

    def __init__(self, code: str) -> None:
        self.code = code
        super().__init__(code)


def _fail(code: str) -> NoReturn:
    raise LegalMatterWorkflowTransitionError(code)


def _text(
    name: str,
    value: object,
    *,
    limit: int = 320,
) -> str:
    if not isinstance(value, str):
        _fail(
            f"G7G_R10_{name.upper()}_INVALID"
        )

    normalized = value.strip()

    if (
        not normalized
        or normalized != value
        or len(normalized) > limit
    ):
        _fail(
            f"G7G_R10_{name.upper()}_INVALID"
        )

    return normalized


def _optional_text(
    name: str,
    value: object,
    *,
    limit: int = 320,
) -> str | None:
    if value is None:
        return None

    return _text(
        name,
        value,
        limit=limit,
    )


def _tenant(value: object) -> str:
    tenant = _text(
        "tenant_id",
        value,
        limit=160,
    )

    if tenant.casefold() in {
        "default",
        "global",
        "root",
        "*",
    }:
        _fail("G7G_R10_TENANT_REQUIRED")

    return tenant


def _positive_int(
    name: str,
    value: object,
) -> int:
    if (
        isinstance(value, bool)
        or not isinstance(value, int)
        or value < 1
    ):
        _fail(
            f"G7G_R10_{name.upper()}_INVALID"
        )

    return value


def _timestamp(
    name: str,
    value: object,
) -> datetime:
    if (
        not isinstance(value, datetime)
        or value.tzinfo is None
        or value.utcoffset() is None
    ):
        _fail(
            f"G7G_R10_{name.upper()}_INVALID"
        )

    return value.astimezone(
        timezone.utc
    )


def _fingerprint(
    name: str,
    value: object,
) -> str:
    if (
        not isinstance(value, str)
        or len(value) != 128
        or value.lower() != value
    ):
        _fail(
            f"G7G_R10_{name.upper()}_INVALID"
        )

    try:
        int(value, 16)
    except ValueError as error:
        raise LegalMatterWorkflowTransitionError(
            f"G7G_R10_{name.upper()}_INVALID"
        ) from error

    return value


def _optional_fingerprint(
    name: str,
    value: object,
) -> str | None:
    if value is None:
        return None

    return _fingerprint(
        name,
        value,
    )


@dataclass(frozen=True, slots=True)
class LegalMatterWorkflowGateBinding:
    """Exact gate-to-satisfaction evidence used to admit a transition."""

    gate_reference: str
    gate_satisfaction_id: str
    gate_satisfaction_fingerprint: str

    def __post_init__(self) -> None:
        object.__setattr__(
            self,
            "gate_reference",
            _text(
                "gate_reference",
                self.gate_reference,
            ),
        )

        object.__setattr__(
            self,
            "gate_satisfaction_id",
            _text(
                "gate_satisfaction_id",
                self.gate_satisfaction_id,
                limit=160,
            ),
        )

        object.__setattr__(
            self,
            "gate_satisfaction_fingerprint",
            _fingerprint(
                "gate_satisfaction_fingerprint",
                self.gate_satisfaction_fingerprint,
            ),
        )

    @classmethod
    def from_satisfaction(
        cls,
        satisfaction: LegalWorkflowGateSatisfaction,
    ) -> "LegalMatterWorkflowGateBinding":
        return cls(
            gate_reference=
                satisfaction.gate_reference,
            gate_satisfaction_id=
                satisfaction.gate_satisfaction_id,
            gate_satisfaction_fingerprint=
                satisfaction.fingerprint,
        )

    def to_dict(
        self,
    ) -> dict[str, object]:
        return {
            "gate_reference":
                self.gate_reference,
            "gate_satisfaction_id":
                self.gate_satisfaction_id,
            "gate_satisfaction_fingerprint":
                self.gate_satisfaction_fingerprint,
        }

    @classmethod
    def from_dict(
        cls,
        value: object,
    ) -> "LegalMatterWorkflowGateBinding":
        if not isinstance(value, dict):
            _fail(
                "G7G_R10_GATE_BINDING_PAYLOAD_INVALID"
            )

        required = {
            "gate_reference",
            "gate_satisfaction_id",
            "gate_satisfaction_fingerprint",
        }

        if set(value) != required:
            _fail(
                "G7G_R10_GATE_BINDING_PAYLOAD_SCHEMA_INVALID"
            )

        return cls(
            gate_reference=value[
                "gate_reference"
            ],
            gate_satisfaction_id=value[
                "gate_satisfaction_id"
            ],
            gate_satisfaction_fingerprint=value[
                "gate_satisfaction_fingerprint"
            ],
        )


@dataclass(frozen=True, slots=True)
class LegalMatterWorkflowTransition:
    """One immutable, chained workflow-stage transition fact."""

    transition_id: str

    tenant_id: str
    case_matter_id: str

    workflow_instance_id: str
    workflow_instance_fingerprint: str
    workflow_topology_fingerprint: str

    sequence_number: int
    previous_transition_fingerprint: str | None

    source_stage_definition_id: str
    source_stage_fingerprint: str

    target_stage_definition_id: str
    target_stage_fingerprint: str

    gate_bindings: tuple[
        LegalMatterWorkflowGateBinding,
        ...
    ]

    branch_selection_evidence_reference: str | None

    transitioned_at: datetime
    transitioned_by_principal_id: str
    transition_authorization_evidence_reference: str

    schema: str = SCHEMA
    workflow_transition_version: str = VERSION
    fingerprint: str = ""

    def __post_init__(self) -> None:
        transition_id = _text(
            "transition_id",
            self.transition_id,
            limit=160,
        )

        tenant_id = _tenant(
            self.tenant_id
        )

        case_matter_id = _text(
            "case_matter_id",
            self.case_matter_id,
            limit=160,
        )

        workflow_instance_id = _text(
            "workflow_instance_id",
            self.workflow_instance_id,
            limit=160,
        )

        workflow_instance_fingerprint = _fingerprint(
            "workflow_instance_fingerprint",
            self.workflow_instance_fingerprint,
        )

        workflow_topology_fingerprint = _fingerprint(
            "workflow_topology_fingerprint",
            self.workflow_topology_fingerprint,
        )

        sequence_number = _positive_int(
            "sequence_number",
            self.sequence_number,
        )

        previous_transition_fingerprint = (
            _optional_fingerprint(
                "previous_transition_fingerprint",
                self.previous_transition_fingerprint,
            )
        )

        if (
            sequence_number == 1
            and previous_transition_fingerprint is not None
        ):
            _fail(
                "G7G_R10_FIRST_TRANSITION_PREVIOUS_FINGERPRINT_FORBIDDEN"
            )

        if (
            sequence_number > 1
            and previous_transition_fingerprint is None
        ):
            _fail(
                "G7G_R10_LATER_TRANSITION_PREVIOUS_FINGERPRINT_REQUIRED"
            )

        source_stage_definition_id = _text(
            "source_stage_definition_id",
            self.source_stage_definition_id,
            limit=160,
        )

        source_stage_fingerprint = _fingerprint(
            "source_stage_fingerprint",
            self.source_stage_fingerprint,
        )

        target_stage_definition_id = _text(
            "target_stage_definition_id",
            self.target_stage_definition_id,
            limit=160,
        )

        target_stage_fingerprint = _fingerprint(
            "target_stage_fingerprint",
            self.target_stage_fingerprint,
        )

        if (
            source_stage_definition_id
            == target_stage_definition_id
        ):
            _fail(
                "G7G_R10_SOURCE_TARGET_SAME_STAGE_INVALID"
            )

        if not isinstance(
            self.gate_bindings,
            tuple,
        ):
            _fail(
                "G7G_R10_GATE_BINDINGS_INVALID"
            )

        bindings: list[
            LegalMatterWorkflowGateBinding
        ] = []

        seen_gates: set[str] = set()

        for binding in self.gate_bindings:
            if not isinstance(
                binding,
                LegalMatterWorkflowGateBinding,
            ):
                _fail(
                    "G7G_R10_GATE_BINDINGS_INVALID"
                )

            if (
                binding.gate_reference
                in seen_gates
            ):
                _fail(
                    "G7G_R10_GATE_BINDING_DUPLICATE"
                )

            seen_gates.add(
                binding.gate_reference
            )

            bindings.append(binding)

        canonical_bindings = tuple(
            sorted(
                bindings,
                key=lambda value:
                    value.gate_reference,
            )
        )

        branch_reference = _optional_text(
            "branch_selection_evidence_reference",
            self.branch_selection_evidence_reference,
        )

        transitioned_at = _timestamp(
            "transitioned_at",
            self.transitioned_at,
        )

        transitioned_by_principal_id = _text(
            "transitioned_by_principal_id",
            self.transitioned_by_principal_id,
            limit=160,
        )

        authorization_reference = _text(
            "transition_authorization_evidence_reference",
            self.transition_authorization_evidence_reference,
        )

        if (
            self.schema != SCHEMA
            or self.workflow_transition_version
            != VERSION
        ):
            _fail(
                "G7G_R10_IDENTITY_INVALID"
            )

        object.__setattr__(
            self,
            "transition_id",
            transition_id,
        )
        object.__setattr__(
            self,
            "tenant_id",
            tenant_id,
        )
        object.__setattr__(
            self,
            "case_matter_id",
            case_matter_id,
        )
        object.__setattr__(
            self,
            "workflow_instance_id",
            workflow_instance_id,
        )
        object.__setattr__(
            self,
            "workflow_instance_fingerprint",
            workflow_instance_fingerprint,
        )
        object.__setattr__(
            self,
            "workflow_topology_fingerprint",
            workflow_topology_fingerprint,
        )
        object.__setattr__(
            self,
            "sequence_number",
            sequence_number,
        )
        object.__setattr__(
            self,
            "previous_transition_fingerprint",
            previous_transition_fingerprint,
        )
        object.__setattr__(
            self,
            "source_stage_definition_id",
            source_stage_definition_id,
        )
        object.__setattr__(
            self,
            "source_stage_fingerprint",
            source_stage_fingerprint,
        )
        object.__setattr__(
            self,
            "target_stage_definition_id",
            target_stage_definition_id,
        )
        object.__setattr__(
            self,
            "target_stage_fingerprint",
            target_stage_fingerprint,
        )
        object.__setattr__(
            self,
            "gate_bindings",
            canonical_bindings,
        )
        object.__setattr__(
            self,
            "branch_selection_evidence_reference",
            branch_reference,
        )
        object.__setattr__(
            self,
            "transitioned_at",
            transitioned_at,
        )
        object.__setattr__(
            self,
            "transitioned_by_principal_id",
            transitioned_by_principal_id,
        )
        object.__setattr__(
            self,
            "transition_authorization_evidence_reference",
            authorization_reference,
        )

        digest = self._compute_fingerprint()

        if self.fingerprint:
            supplied = _fingerprint(
                "fingerprint",
                self.fingerprint,
            )

            if not hmac.compare_digest(
                supplied,
                digest,
            ):
                _fail(
                    "G7G_R10_FINGERPRINT_MISMATCH"
                )

        object.__setattr__(
            self,
            "fingerprint",
            digest,
        )

    @classmethod
    def from_authorities(
        cls,
        *,
        transition_id: str,
        workflow_instance:
            LegalMatterWorkflowInstance,
        workflow_topology:
            LegalWorkflowTopology,
        source_stage:
            LegalWorkflowStage,
        target_stage:
            LegalWorkflowStage,
        gate_satisfactions: tuple[
            LegalWorkflowGateSatisfaction,
            ...
        ],
        transitioned_at: datetime,
        transitioned_by_principal_id: str,
        transition_authorization_evidence_reference: str,
        branch_selection_evidence_reference:
            str | None = None,
        previous_transition:
            "LegalMatterWorkflowTransition | None" = None,
    ) -> "LegalMatterWorkflowTransition":
        """Admit one exact local transition from already-proven authorities."""
        if not hmac.compare_digest(
            workflow_instance.workflow_topology_fingerprint,
            workflow_topology.fingerprint,
        ):
            _fail(
                "G7G_R10_INSTANCE_TOPOLOGY_BINDING_MISMATCH"
            )

        topology_stage_map = {
            value.stage_definition_id: value
            for value in workflow_topology.stages
        }

        source_topology = topology_stage_map.get(
            source_stage.stage_definition_id
        )

        target_topology = topology_stage_map.get(
            target_stage.stage_definition_id
        )

        if source_topology is None:
            _fail(
                "G7G_R10_SOURCE_STAGE_NOT_IN_TOPOLOGY"
            )

        if target_topology is None:
            _fail(
                "G7G_R10_TARGET_STAGE_NOT_IN_TOPOLOGY"
            )

        if not hmac.compare_digest(
            source_topology.stage_fingerprint,
            source_stage.fingerprint,
        ):
            _fail(
                "G7G_R10_SOURCE_STAGE_FINGERPRINT_MISMATCH"
            )

        if not hmac.compare_digest(
            target_topology.stage_fingerprint,
            target_stage.fingerprint,
        ):
            _fail(
                "G7G_R10_TARGET_STAGE_FINGERPRINT_MISMATCH"
            )

        if (
            target_stage.stage_definition_id
            not in source_stage.successor_stage_ids
        ):
            _fail(
                "G7G_R10_TARGET_NOT_CERTIFIED_SUCCESSOR"
            )

        if previous_transition is None:
            sequence_number = 1
            previous_fingerprint = None

            if (
                source_stage.stage_definition_id
                != workflow_instance.entry_stage_definition_id
            ):
                _fail(
                    "G7G_R10_FIRST_TRANSITION_SOURCE_NOT_ENTRY"
                )
        else:
            if (
                previous_transition.tenant_id
                != workflow_instance.tenant_id
                or previous_transition.case_matter_id
                != workflow_instance.case_matter_id
                or previous_transition.workflow_instance_id
                != workflow_instance.workflow_instance_id
                or not hmac.compare_digest(
                    previous_transition.workflow_instance_fingerprint,
                    workflow_instance.fingerprint,
                )
                or not hmac.compare_digest(
                    previous_transition.workflow_topology_fingerprint,
                    workflow_topology.fingerprint,
                )
            ):
                _fail(
                    "G7G_R10_PREVIOUS_TRANSITION_SCOPE_MISMATCH"
                )

            if (
                previous_transition.target_stage_definition_id
                != source_stage.stage_definition_id
            ):
                _fail(
                    "G7G_R10_PREVIOUS_TARGET_SOURCE_MISMATCH"
                )

            if (
                previous_transition.transitioned_at
                >= transitioned_at
            ):
                _fail(
                    "G7G_R10_TRANSITION_CHRONOLOGY_INVALID"
                )

            sequence_number = (
                previous_transition.sequence_number + 1
            )

            previous_fingerprint = (
                previous_transition.fingerprint
            )

        configured_gates = tuple(
            source_stage.completion_gate_references
        )

        supplied_by_gate: dict[
            str,
            LegalWorkflowGateSatisfaction,
        ] = {}

        for satisfaction in gate_satisfactions:
            if not isinstance(
                satisfaction,
                LegalWorkflowGateSatisfaction,
            ):
                _fail(
                    "G7G_R10_GATE_SATISFACTION_INVALID"
                )

            if (
                satisfaction.gate_reference
                in supplied_by_gate
            ):
                _fail(
                    "G7G_R10_GATE_SATISFACTION_DUPLICATE"
                )

            if (
                satisfaction.tenant_id
                != workflow_instance.tenant_id
                or satisfaction.case_matter_id
                != workflow_instance.case_matter_id
                or satisfaction.workflow_instance_id
                != workflow_instance.workflow_instance_id
                or not hmac.compare_digest(
                    satisfaction.workflow_instance_fingerprint,
                    workflow_instance.fingerprint,
                )
                or not hmac.compare_digest(
                    satisfaction.workflow_topology_fingerprint,
                    workflow_topology.fingerprint,
                )
            ):
                _fail(
                    "G7G_R10_GATE_SATISFACTION_SCOPE_MISMATCH"
                )

            if (
                satisfaction.source_stage_definition_id
                != source_stage.stage_definition_id
                or not hmac.compare_digest(
                    satisfaction.source_stage_fingerprint,
                    source_stage.fingerprint,
                )
            ):
                _fail(
                    "G7G_R10_GATE_SATISFACTION_STAGE_MISMATCH"
                )

            supplied_by_gate[
                satisfaction.gate_reference
            ] = satisfaction

        if (
            set(supplied_by_gate)
            != set(configured_gates)
        ):
            _fail(
                "G7G_R10_GATE_SATISFACTION_SET_MISMATCH"
            )

        gate_bindings = tuple(
            LegalMatterWorkflowGateBinding.from_satisfaction(
                supplied_by_gate[gate_reference]
            )
            for gate_reference in configured_gates
        )

        successor_count = len(
            source_stage.successor_stage_ids
        )

        if successor_count > 1:
            if branch_selection_evidence_reference is None:
                _fail(
                    "G7G_R10_BRANCH_SELECTION_EVIDENCE_REQUIRED"
                )
        else:
            if branch_selection_evidence_reference is not None:
                _fail(
                    "G7G_R10_BRANCH_SELECTION_EVIDENCE_FORBIDDEN"
                )

        return cls(
            transition_id=
                transition_id,
            tenant_id=
                workflow_instance.tenant_id,
            case_matter_id=
                workflow_instance.case_matter_id,
            workflow_instance_id=
                workflow_instance.workflow_instance_id,
            workflow_instance_fingerprint=
                workflow_instance.fingerprint,
            workflow_topology_fingerprint=
                workflow_topology.fingerprint,
            sequence_number=
                sequence_number,
            previous_transition_fingerprint=
                previous_fingerprint,
            source_stage_definition_id=
                source_stage.stage_definition_id,
            source_stage_fingerprint=
                source_stage.fingerprint,
            target_stage_definition_id=
                target_stage.stage_definition_id,
            target_stage_fingerprint=
                target_stage.fingerprint,
            gate_bindings=
                gate_bindings,
            branch_selection_evidence_reference=
                branch_selection_evidence_reference,
            transitioned_at=
                transitioned_at,
            transitioned_by_principal_id=
                transitioned_by_principal_id,
            transition_authorization_evidence_reference=
                transition_authorization_evidence_reference,
        )

