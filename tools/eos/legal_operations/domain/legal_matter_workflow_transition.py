"""TITLE: WILSY OS Legal Matter Workflow Transition Domain.

VERSION: v1.0.1-G7G-R10-LEGAL-MATTER-WORKFLOW-TRANSITION

AUTHORITY:
    Wilsy OS Core Governance / Python EOS Legal Operations.

EPITOME:
    Preserve one immutable admitted runtime transition between two certified
    stages of one exact LegalMatterWorkflowInstance.

    This domain validates structural progression evidence only.

PROGRESSION MODEL:
    First transition:
        sequence_number == 1
        previous_transition_fingerprint is None
        source stage is the instance entry stage.

    Later transition:
        sequence_number == previous sequence + 1
        previous_transition_fingerprint binds the exact previous transition
        fingerprint
        source stage equals the previous transition target stage.

TOPOLOGY:
    Source and target stages must both belong to the exact topology bound to
    the workflow instance.

    target_stage_definition_id must be one of the certified successor stage
    identifiers of the source stage.

COMPLETION GATES:
    Every completion_gate_reference configured on the source stage must have
    exactly one LegalWorkflowGateSatisfaction binding.

    Missing, extra, duplicate, cross-instance, cross-stage, cross-topology or
    fingerprint-divergent satisfaction evidence rejects.

    A stage with no configured completion gates requires no gate satisfaction.

BRANCHING:
    A source stage with more than one successor requires an explicit
    branch_selection_evidence_reference.

    A source stage with exactly one successor forbids branch-selection
    evidence. This prevents decorative or caller-manufactured branch claims.

CURRENTNESS:
    This transition does not declare itself current and owns no mutable current
    stage. Current workflow position is derived later from the immutable
    instance start plus complete validated transition history.

LEGAL-TRUTH BOUNDARY:
    Transition does not manufacture canonical Legal events, matter state,
    professional authority, assignments, supervision, work completion,
    documents, deadlines or specialist lifecycle truth.

AUTHORIZATION:
    transitioned_by_principal_id and
    transition_authorization_evidence_reference are audit provenance only.
    They are not durable permission and cannot be reused as IAM authority.

WORK:
    No LegalWorkItem is generated by this value.

FINANCIAL AUTHORITY:
    None. Kennel EOS remains exclusive financial execution authority.
"""
